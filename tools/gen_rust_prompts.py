#!/usr/bin/env python3
"""Generate Rust prompt constants from references/eval/tasks_prompts.py.

The Python module is the single source of truth for eval prompt text. This
script transcribes the listed constants into Rust `pub const` declarations,
byte-identical, as raw strings. `references/tests/test_rust_prompt_parity.py`
re-derives the same values at test time and fails the gate on any drift, so
hand-editing either side breaks CI.

Usage: PYTHONPATH=references python3 tools/gen_rust_prompts.py
Exits 1 if any output file would exceed the 500-line production cap.
"""

